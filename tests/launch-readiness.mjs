import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await desktop.goto('http://127.0.0.1:5173/');
  await desktop.keyboard.press('Tab');
  if (!await desktop.locator('.skip-link').evaluate(el => el === document.activeElement)) throw Error('Skip link not first keyboard stop');
  await desktop.keyboard.press('Enter');
  if (!await desktop.locator('#main-content').evaluate(el => el === document.activeElement)) throw Error('Skip target not focused');
  const services = desktop.locator('.desktop-nav .menu-trigger').first();
  await services.focus(); await desktop.keyboard.press('Enter');
  if (await services.getAttribute('aria-expanded') !== 'true' || !await desktop.locator('#inner-mega').isVisible()) throw Error('Mega menu not accessible');
  await desktop.keyboard.press('Escape');
  if (await services.getAttribute('aria-expanded') !== 'false' || !await services.evaluate(el => el === document.activeElement)) throw Error('Escape did not restore menu focus');
  const meta = await desktop.locator('meta[name=robots]').getAttribute('content');
  if (meta !== 'noindex, follow') throw Error('Preview should be noindex');
  if (!await desktop.locator('meta[property=\"og:description\"]').getAttribute('content')) throw Error('Social description missing');
  await desktop.goto('http://127.0.0.1:5173/insights/rmg-product-story/');
  if (await desktop.locator('meta[name=robots]').getAttribute('content') !== 'noindex, follow') throw Error('Fictional story should be noindex');
  if (!(await desktop.title()).includes('Fictional Story')) throw Error('Fictional story needs distinctive title');
  await desktop.goto('http://127.0.0.1:5173/contact/?topic=rmg');
  await desktop.locator('.lead-form input').nth(0).fill('Test Person');
  await desktop.locator('.lead-form input').nth(1).fill('test@example.com');
  await desktop.locator('.lead-form input').nth(2).fill('Example Co');
  await desktop.locator('.lead-form textarea').first().fill('Exploring a product-data pilot.');
  await desktop.getByRole('button', { name: 'Open email draft' }).click();
  if (!await desktop.locator('.email-fallback').isVisible()) throw Error('Email fallback not shown');
  const prepared = await desktop.locator('.email-fallback textarea').inputValue();
  if (!prepared.includes('RMG product-data readiness') || !prepared.includes('Exploring a product-data pilot.')) throw Error('Email draft lacks context');
  await desktop.close();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await mobile.goto('http://127.0.0.1:5173/');
  const toggle = mobile.locator('.mobile-toggle');
  await toggle.click();
  if (await toggle.getAttribute('aria-expanded') !== 'true') throw Error('Mobile nav did not open');
  await mobile.keyboard.press('Escape');
  if (await toggle.getAttribute('aria-expanded') !== 'false' || !await toggle.evaluate(el => el === document.activeElement)) throw Error('Mobile nav focus not restored');
  const dock = mobile.getByRole('button', { name: 'Open quick actions' });
  await dock.click(); await mobile.keyboard.press('Escape');
  if (!await dock.evaluate(el => el === document.activeElement)) throw Error('Dock focus not restored');
  await mobile.close();
  console.log('PASS: keyboard menus, skip link, preview indexing safeguards and contact fallback');
} finally { await browser.close(); }
